-- Role-specific employee ID formats and a deterministic backfill for existing users.
CREATE TABLE IF NOT EXISTS ERM_EMPLOYEE_ID_ROLE_FORMATS (
    ROLE_NAME VARCHAR(100) NOT NULL PRIMARY KEY,
    ID_PREFIX VARCHAR(20) NOT NULL,
    SEQUENCE_ENABLED TINYINT(1) NOT NULL,
    PRIORITY_ORDER INT NOT NULL
);

