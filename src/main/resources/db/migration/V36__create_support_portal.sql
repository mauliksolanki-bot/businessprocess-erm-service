-- ---------------------------------------------------------------------------
-- 2. Support catalog and queues
-- ---------------------------------------------------------------------------
CREATE TABLE ERM_SUPPORT_CATEGORIES (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    CATEGORY_CODE VARCHAR(100) NOT NULL UNIQUE,
    CATEGORY_TITLE VARCHAR(120) NOT NULL,
    TICKET_TYPE VARCHAR(50) NOT NULL,
    PARENT_CATEGORY_CODE VARCHAR(100) NULL,
    SORT_ORDER INT NOT NULL DEFAULT 0,
    IS_ACTIVE TINYINT(1) NOT NULL DEFAULT 1,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ERM_SUPPORT_QUEUES (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    QUEUE_CODE VARCHAR(100) NOT NULL UNIQUE,
    QUEUE_TITLE VARCHAR(120) NOT NULL,
    QUEUE_TYPE VARCHAR(50) NOT NULL,
    DESCRIPTION VARCHAR(255) NULL,
    IS_ACTIVE TINYINT(1) NOT NULL DEFAULT 1,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ERM_SUPPORT_QUEUE_MEMBERS (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    QUEUE_ID BIGINT NOT NULL,
    USER_ID BIGINT NOT NULL,
    IS_ACTIVE TINYINT(1) NOT NULL DEFAULT 1,
    LAST_ASSIGNED_AT TIMESTAMP NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_ERM_SUPPORT_QUEUE_MEMBERS_QUEUE FOREIGN KEY (QUEUE_ID) REFERENCES ERM_SUPPORT_QUEUES (ID),
    CONSTRAINT FK_ERM_SUPPORT_QUEUE_MEMBERS_USER FOREIGN KEY (USER_ID) REFERENCES ERM_USERS (ID),
    UNIQUE KEY UK_ERM_SUPPORT_QUEUE_MEMBERS (QUEUE_ID, USER_ID)
);

CREATE TABLE ERM_SUPPORT_PRIORITY_MATRIX (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    IMPACT_LEVEL VARCHAR(20) NOT NULL,
    URGENCY_LEVEL VARCHAR(20) NOT NULL,
    PRIORITY_CODE VARCHAR(20) NOT NULL,
    IS_ACTIVE TINYINT(1) NOT NULL DEFAULT 1,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY UK_ERM_SUPPORT_PRIORITY_MATRIX (IMPACT_LEVEL, URGENCY_LEVEL)
);

CREATE TABLE ERM_SUPPORT_SLA_POLICIES (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    QUEUE_CODE VARCHAR(100) NOT NULL,
    TICKET_TYPE VARCHAR(50) NOT NULL,
    PRIORITY_CODE VARCHAR(20) NOT NULL,
    RESPONSE_MINUTES INT NOT NULL,
    RESOLUTION_MINUTES INT NOT NULL,
    IS_ACTIVE TINYINT(1) NOT NULL DEFAULT 1,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY UK_ERM_SUPPORT_SLA_POLICIES (QUEUE_CODE, TICKET_TYPE, PRIORITY_CODE)
);

CREATE TABLE ERM_SUPPORT_ESCALATION_RULES (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    QUEUE_CODE VARCHAR(100) NOT NULL,
    PRIORITY_CODE VARCHAR(20) NOT NULL,
    WARN_MINUTES INT NOT NULL,
    BREACH_MINUTES INT NOT NULL,
    ESCALATE_TO_ROLE_NAME VARCHAR(100) NOT NULL,
    IS_ACTIVE TINYINT(1) NOT NULL DEFAULT 1,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY UK_ERM_SUPPORT_ESCALATION_RULES (QUEUE_CODE, PRIORITY_CODE)
);

