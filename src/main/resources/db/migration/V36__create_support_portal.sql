-- ---------------------------------------------------------------------------
-- 4. Support ticketing tables
-- ---------------------------------------------------------------------------
CREATE TABLE ERM_SUPPORT_TICKETS (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    TICKET_NUMBER VARCHAR(30) NOT NULL UNIQUE,
    REQUESTER_USER_ID BIGINT NOT NULL,
    REQUESTER_USERNAME VARCHAR(100) NOT NULL,
    REQUESTER_FULL_NAME VARCHAR(150) NOT NULL,
    TICKET_TYPE VARCHAR(50) NOT NULL,
    CATEGORY_CODE VARCHAR(100) NOT NULL,
    CATEGORY_TITLE VARCHAR(120) NOT NULL,
    SUBCATEGORY_CODE VARCHAR(100) NULL,
    SUBCATEGORY_TITLE VARCHAR(120) NULL,
    IMPACT_LEVEL VARCHAR(20) NOT NULL,
    URGENCY_LEVEL VARCHAR(20) NOT NULL,
    PRIORITY_CODE VARCHAR(20) NOT NULL,
    QUEUE_ID BIGINT NOT NULL,
    QUEUE_CODE VARCHAR(100) NOT NULL,
    QUEUE_TITLE VARCHAR(120) NOT NULL,
    ASSIGNEE_USER_ID BIGINT NULL,
    ASSIGNEE_USERNAME VARCHAR(100) NULL,
    ASSIGNEE_FULL_NAME VARCHAR(150) NULL,
    STATUS VARCHAR(50) NOT NULL,
    SOURCE VARCHAR(50) NOT NULL,
    SHORT_DESCRIPTION VARCHAR(255) NOT NULL,
    DESCRIPTION TEXT NOT NULL,
    SECURITY_INCIDENT TINYINT(1) NOT NULL DEFAULT 0,
    RESPONSE_DUE_AT TIMESTAMP NULL,
    RESOLUTION_DUE_AT TIMESTAMP NULL,
    FIRST_RESPONSE_AT TIMESTAMP NULL,
    RESOLVED_AT TIMESTAMP NULL,
    CLOSED_AT TIMESTAMP NULL,
    CREATED_BY_USERNAME VARCHAR(100) NOT NULL,
    UPDATED_BY_USERNAME VARCHAR(100) NOT NULL,
    VERSION BIGINT NOT NULL DEFAULT 0,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT FK_ERM_SUPPORT_TICKETS_QUEUE FOREIGN KEY (QUEUE_ID) REFERENCES ERM_SUPPORT_QUEUES (ID),
    CONSTRAINT FK_ERM_SUPPORT_TICKETS_REQUESTER FOREIGN KEY (REQUESTER_USER_ID) REFERENCES ERM_USERS (ID),
    CONSTRAINT FK_ERM_SUPPORT_TICKETS_ASSIGNEE FOREIGN KEY (ASSIGNEE_USER_ID) REFERENCES ERM_USERS (ID)
);

CREATE TABLE ERM_SUPPORT_TICKET_COMMENTS (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    TICKET_ID BIGINT NOT NULL,
    ACTOR_USERNAME VARCHAR(100) NOT NULL,
    ACTION_TYPE VARCHAR(50) NOT NULL,
    COMMENT_TEXT VARCHAR(1000) NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_ERM_SUPPORT_TICKET_COMMENTS_TICKET FOREIGN KEY (TICKET_ID) REFERENCES ERM_SUPPORT_TICKETS (ID)
);

CREATE TABLE ERM_SUPPORT_AUDIT_LOG (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    TICKET_ID BIGINT NOT NULL,
    ACTOR_USERNAME VARCHAR(100) NOT NULL,
    ACTION_TYPE VARCHAR(50) NOT NULL,
    FROM_STATUS VARCHAR(50) NULL,
    TO_STATUS VARCHAR(50) NULL,
    DETAILS VARCHAR(1000) NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_ERM_SUPPORT_AUDIT_LOG_TICKET FOREIGN KEY (TICKET_ID) REFERENCES ERM_SUPPORT_TICKETS (ID)
);

CREATE TABLE ERM_SUPPORT_NOTIFICATIONS (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    TICKET_ID BIGINT NOT NULL,
    RECIPIENT_USERNAME VARCHAR(100) NOT NULL,
    CHANNEL VARCHAR(20) NOT NULL,
    EVENT_TYPE VARCHAR(50) NOT NULL,
    MESSAGE_TEXT VARCHAR(1000) NOT NULL,
    READ_AT TIMESTAMP NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_ERM_SUPPORT_NOTIFICATIONS_TICKET FOREIGN KEY (TICKET_ID) REFERENCES ERM_SUPPORT_TICKETS (ID)
);
